-- Deliver IndexNow notifications from a durable, deduplicated queue.  This
-- prevents a post edit from issuing an outbound request immediately and lets
-- the worker back off safely when IndexNow returns HTTP 429.
create table if not exists public.indexnow_url_queue (
  id bigint generated by default as identity primary key,
  url text not null unique,
  status text not null default 'pending'
    check (status in ('pending', 'processing', 'sent', 'failed')),
  attempt_count integer not null default 0 check (attempt_count >= 0),
  next_attempt_at timestamptz not null default current_timestamp,
  lock_token text,
  locked_at timestamptz,
  last_error text,
  sent_at timestamptz,
  created_at timestamptz not null default current_timestamp,
  updated_at timestamptz not null default current_timestamp
);

create index if not exists idx_indexnow_url_queue_pending
  on public.indexnow_url_queue (next_attempt_at, id)
  where status = 'pending';

alter table public.indexnow_url_queue enable row level security;
