-- Initial schema reproduced from the verified production backup.
-- Application tables stay private: all access is through the server/Worker.

create function public.update_updated_at_column()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = current_timestamp;
  return new;
end;
$$;

create table public.admins (
  id integer generated by default as identity primary key,
  username varchar(50) not null unique,
  password varchar(255) not null,
  created_at timestamptz default current_timestamp
);

create table public.categories (
  id integer generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  is_visible boolean default true,
  sort_order integer default 0,
  created_at timestamptz default current_timestamp
);

create table public.posts (
  id integer generated by default as identity primary key,
  title varchar(255) not null,
  content text not null,
  thumbnail_url text,
  created_at timestamptz default current_timestamp,
  updated_at timestamptz default current_timestamp,
  slug varchar(255) unique,
  meta_title varchar(255),
  meta_description text,
  views integer default 0,
  status varchar(20) default 'published',
  deleted_at timestamptz,
  likes integer default 0,
  published_at timestamptz default current_timestamp,
  category_id integer references public.categories(id) on delete set null
);

create index idx_posts_slug on public.posts (slug);

create trigger update_posts_updated_at
before update on public.posts
for each row execute function public.update_updated_at_column();

create table public.comments (
  id integer generated by default as identity primary key,
  post_id integer references public.posts(id) on delete cascade,
  author_name text not null,
  content text not null,
  password text not null,
  is_admin boolean default false,
  created_at timestamptz default current_timestamp,
  reports integer default 0,
  is_private boolean default false,
  deleted_at timestamptz,
  likes integer default 0
);

create index idx_comments_post_id on public.comments (post_id);
create index idx_comments_reports on public.comments (reports);

create table public.post_views (
  id integer generated by default as identity primary key,
  post_id integer references public.posts(id),
  ip_address text,
  viewed_at timestamptz default current_timestamp,
  unique (post_id, ip_address)
);

create index idx_post_views_post_id on public.post_views (post_id);
create index idx_post_views_ip_address on public.post_views (ip_address);

create table public.visitor_logs (
  id integer generated by default as identity primary key,
  session_id text not null,
  post_id integer references public.posts(id) on delete set null,
  path text not null,
  ip_address text,
  user_agent text,
  referrer text,
  device_type text,
  created_at timestamptz default current_timestamp,
  browser text,
  os text,
  device_model text
);

create index idx_visitor_logs_created_at on public.visitor_logs (created_at);
create index idx_visitor_logs_session_id on public.visitor_logs (session_id);
create index idx_visitor_logs_post_id on public.visitor_logs (post_id);

create table public.bamboo_posts (
  id integer generated by default as identity primary key,
  author_name varchar(50) not null,
  content text not null,
  password text not null,
  client_token text not null,
  created_at timestamptz default current_timestamp,
  updated_at timestamptz default current_timestamp,
  likes integer default 0 not null,
  seo_title varchar(255),
  slug varchar(255),
  meta_title varchar(255),
  meta_description text,
  meta_keywords text[],
  summary text,
  category varchar(50),
  tags text[],
  seo_status varchar(20) default 'pending' not null,
  indexable boolean default true not null,
  ai_generated_at timestamptz,
  ai_model varchar(50),
  ai_error text,
  seo_locked boolean default false not null,
  content_hash varchar(64)
);

create index idx_bamboo_posts_created_at on public.bamboo_posts (created_at desc);
create index idx_bamboo_posts_slug on public.bamboo_posts (slug);
create index idx_bamboo_posts_seo_status on public.bamboo_posts (seo_status);

create table public.bamboo_comments (
  id integer generated by default as identity primary key,
  bamboo_post_id integer references public.bamboo_posts(id) on delete cascade,
  parent_id integer references public.bamboo_comments(id) on delete cascade,
  author_name varchar(50) not null,
  content text not null,
  password text not null,
  client_token text not null,
  created_at timestamptz default current_timestamp,
  updated_at timestamptz default current_timestamp
);

create index idx_bamboo_comments_post_id on public.bamboo_comments (bamboo_post_id);
create index idx_bamboo_comments_parent_id on public.bamboo_comments (parent_id);

create table public.forbidden_words (
  id integer generated by default as identity primary key,
  word varchar(100) not null unique,
  category varchar(50) default 'other' not null,
  created_at timestamptz default current_timestamp
);

create table public.indexing_schedules (
  id integer primary key default 1,
  scheduled_hour integer default 3 not null check (scheduled_hour between 0 and 23),
  enabled boolean default true not null,
  updated_at timestamptz default current_timestamp
);

create table public.indexing_logs (
  id integer generated by default as identity primary key,
  trigger_type varchar(20) not null,
  status varchar(20) not null,
  message text,
  url_count integer default 0 not null,
  created_at timestamptz default current_timestamp
);

